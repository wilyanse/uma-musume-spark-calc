#!/usr/bin/env python3
"""Generates test/fingerprint.vectors.json WITHOUT using the TypeScript implementation.

Canonical JSON is built here with json.dumps(sort_keys=True, separators=(',', ':'), ensure_ascii=False)
from the 01 §5 recipe, and each sha256 is then re-computed with `printf '%s' <canonical> | shasum -a 256`
and the two must agree. Run: python3 scripts/make-vectors.py
"""
import copy, hashlib, json, subprocess, pathlib

APT = ["turf","dirt","sprint","mile","medium","long","front","pace","late","end"]
STAT = ["spd","sta","pow","gut","wit"]

def base():
    return {
        "characterId": "character:mejiro-mcqueen", "outfitId": "outfit:frontline-elegance",
        "rank": "A+", "rating": 12500, "epithet": "Independent Learner", "trainMode": "independent",
        "stats": {"spd": 1100, "sta": 800, "pow": 900, "gut": 400, "wit": 700},
        "aptitudes": dict(zip(APT, ["A","G","G","A","A","C","G","A","B","G"])),
        "skills": [{"skillId": "skill:example-skill", "level": None}],
        "sparks": [
            {"owner":"self","sparkId":"spark:speed","type":"blue","stars":3},
            {"owner":"self","sparkId":"spark:turf","type":"pink","stars":2},
            {"owner":"parent1","sparkId":"spark:stamina","type":"blue","stars":2},
            {"owner":"parent1","sparkId":"spark:medium","type":"pink","stars":1},
            {"owner":"parent2","sparkId":"spark:power","type":"blue","stars":1},
            {"owner":"parent2","sparkId":"spark:pace","type":"pink","stars":3},
        ],
        "deck": [{"slot":i,"cardId":"card:example-card","lb":0,"level":1,"borrowed":False} for i in range(1,7)],
        "parents": [
            {"slot":1,"characterId":"character:special-week","outfitId":"outfit:special-week-base","isGuest":False,"guestTrainer":None},
            {"slot":2,"characterId":"character:silence-suzuka","outfitId":"outfit:silence-suzuka-base","isGuest":False,"guestTrainer":None},
        ],
        "scenarioId": "scenario:ura-finale",
        "career": {"races": 40, "wins": 30, "fans": 1000000, "dateAcquired": "2026-09-01"},
    }

def payload(v):
    p = {p["slot"]: p["characterId"] for p in v["parents"]}
    return {"c": v["characterId"], "o": v["outfitId"], "s": [v["stats"][k] for k in STAT],
            "a": [v["aptitudes"][k] for k in APT],
            "sp": sorted(f'{s["owner"]}|{s["sparkId"]}|{s["stars"]}' for s in v["sparks"]),
            "p": [p[1], p[2]], "d": v["career"]["dateAcquired"]}

vectors = []
def add(name, v, note):
    canon = json.dumps(payload(v), sort_keys=True, separators=(",", ":"), ensure_ascii=False)
    sha = hashlib.sha256(canon.encode()).hexdigest()
    sh = subprocess.run(["shasum","-a","256"], input=canon.encode(), capture_output=True).stdout.decode().split()[0]
    assert sha == sh, name
    vectors.append({"name": name, "note": note, "input": v, "canonical": canon, "sha256": sha})

v = base(); add("baseline", v, "Two owned parents, 3-star blue.")

v = base(); v["sparks"] = list(reversed(v["sparks"]))
add("baseline-sparks-permuted", v, "Same as baseline with sparks in reverse order: must hash identically.")

v = base(); v["parents"][1].update({"characterId":"character:guest-example","outfitId":None,"isGuest":True,"guestTrainer":"Some Trainer"})
add("guest-parent", v, "Parent 2 is a guest: outfitId null, guestTrainer set.")

v = base(); v["skills"] = [{"skillId":"skill:concentration-2","level":None},{"skillId":"skill:unique-example","level":2}]
add("skill-circle-suffix", v, "Skills include a collision-suffixed ID (`-2`, the slug of a game name ending in \u25ef, since ID slugs collapse non-alphanumerics, 01 §1) and a unique level; skills are not part of the fingerprint, so the hash equals a skill-less veteran with the same other fields but is listed to prove the payload ignores them.")

v = base(); v["sparks"][0]["stars"] = 2
add("blue-2-star", v, "Baseline with the self blue spark at 2 stars.")

v = base(); v["sparks"][0]["stars"] = 3; v["sparks"][1]["stars"] = 3
add("pink-3-star-vs-2-star", v, "Baseline with self pink at 3 stars instead of 2; differs from baseline.")

v = base(); v["epithet"] = "Late Bloomer"; v["trainMode"] = "manual"; v["stats"]["wit"] = 2000; v["career"]["dateAcquired"] = "2026-01-31"
add("manual-mode-max-stat", v, "Manual mode, wit at the 2000 cap, different date.")

out = {
  "description": "Fingerprint vectors shared by the TypeScript and C# test suites (01 §5).",
  "provenance": "Generated by scripts/make-vectors.py, which builds the canonical JSON with Python json.dumps(sort_keys=True, separators=(',',':')) and computes sha256 twice: hashlib and `printf '%s' '<canonical>' | shasum -a 256`. The TypeScript implementation is not involved. Regenerate with `python3 scripts/make-vectors.py`.",
  "vectors": vectors,
}
path = pathlib.Path(__file__).resolve().parent.parent / "test" / "fingerprint.vectors.json"
path.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n")
print("wrote", len(vectors), "vectors")
