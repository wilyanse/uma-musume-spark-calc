#!/usr/bin/env python3
"""Reproducible stdlib rendering of the shipped Windows SDK RTF (not a general RTF converter).

Preserve text, Unicode and paragraph breaks; omit formatting, metadata, list labels and field
instructions (displayed field results remain). Run: python render_sdk_license.py INPUT.rtf OUTPUT.txt
The original RTF remains authoritative. This derived rendering does not replace its licence.
"""
import re
import sys
from pathlib import Path

SKIP = {'fonttbl', 'colortbl', 'stylesheet', 'info', 'pict', 'object', 'header', 'footer',
        'listtext', 'pntext', 'fldinst', 'ftnsep', 'ftnsepc'}
TOKENS = re.compile(r"\\([a-zA-Z]+)(-?\d+)? ?|\\'([0-9a-fA-F]{2})|\\([^a-zA-Z])|([{}])|([^\\{}]+)")


def render(data):
    s = data.decode('ascii')
    stack = []
    skip, uc, fallback = False, 1, 0
    out = []
    for m in TOKENS.finditer(s):
        word, arg, hx, sym, brace, text = m.groups()
        if brace == '{':
            stack.append((skip, uc))
        elif brace == '}':
            if not stack:
                raise ValueError('unbalanced RTF')
            skip, uc = stack.pop()
        elif sym == '*':
            skip = True
        elif word in SKIP:
            skip = True
        elif word == 'uc':
            uc = int(arg)
        elif word == 'u':
            if not skip:
                out.append(chr(int(arg) % 65536))
                fallback = uc
        elif word in ('par', 'line', 'page'):
            if not skip:
                out.append('\n')
        elif word == 'tab':
            if not skip:
                out.append('\t')
        elif word in ('endash', 'emdash', 'rquote', 'lquote', 'rdblquote', 'ldblquote'):
            if not skip:
                out.append({'endash': '–', 'emdash': '—', 'rquote': '’', 'lquote': '‘',
                            'rdblquote': '”', 'ldblquote': '“'}[word])
        elif hx or sym or text:
            if skip:
                continue
            chunk = bytes.fromhex(hx).decode('cp1252') if hx else (
                {'~': '\u00a0', '_': '‑', '-': ''}.get(sym, sym) if sym else text.replace('\r', '').replace('\n', ''))
            if fallback:
                n = min(len(chunk), fallback)
                chunk = chunk[n:]
                fallback -= n
            if not skip:
                out.append(chunk)
    if stack:
        raise ValueError('unbalanced RTF')
    body = '\n'.join(line.rstrip() for line in ''.join(out).strip().splitlines()) + '\n'
    return ('DERIVED PLAIN-TEXT RENDERING — original RTF is authoritative.\n'
            'Generated by agent/legal/tools/render_sdk_license.py (Python stdlib).\n'
            'Formatting and generated list labels omitted; wording unchanged.\n\n' + body).encode('utf-8')


if __name__ == '__main__':
    Path(sys.argv[2]).write_bytes(render(Path(sys.argv[1]).read_bytes()))
