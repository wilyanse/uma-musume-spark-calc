using System.Buffers.Binary;
using Xunit;

namespace Uma.Agent.Core.Tests;

public class PngIngressEndTests
{
    [Fact]
    public void Initial_oversize_is_refused_before_reading_or_allocating_encoded_storage()
    {
        using var s = new ChangingStream(33, new byte[33]);
        var before = GC.GetAllocatedBytesForCurrentThread();
        Assert.Throws<InvalidDataException>(() => Frames.ReadEncoded(s, 32));
        Assert.Equal(0, s.ReadBytes);
        Assert.True(GC.GetAllocatedBytesForCurrentThread() - before < 100_000);
    }

    [Theory]
    [InlineData(2, 33)]
    [InlineData(32, 33)]
    public void Growth_is_refused_with_at_most_the_cap_plus_one_probe_byte(int initial, int actual)
    {
        using var s = new ChangingStream(initial, new byte[actual]);
        Assert.Throws<InvalidDataException>(() => Frames.ReadEncoded(s, 32));
        Assert.InRange(s.ReadBytes, 0, 33);
    }

    [Fact]
    public void Shrink_and_short_reads_return_only_actual_bytes()
    {
        using var s = new ChangingStream(32, [1, 2, 3]);
        Assert.Equal(new byte[] { 1, 2, 3 }, Frames.ReadEncoded(s, 32));
    }

    [Fact]
    public void Nonseekable_stream_is_explicitly_unsupported_without_reading()
    {
        using var s = new ChangingStream(0, [1], false);
        Assert.Throws<NotSupportedException>(() => Frames.ReadEncoded(s, 32));
        Assert.Equal(0, s.ReadBytes);
    }

    private sealed class ChangingStream(long initialLength, byte[] bytes, bool seekable = true) : Stream
    {
        private int position;
        public int ReadBytes => position;
        public override bool CanRead => true;
        public override bool CanSeek => seekable;
        public override bool CanWrite => false;
        public override long Length => initialLength;
        public override long Position { get => position; set => throw new NotSupportedException(); }
        public override int Read(byte[] buffer, int offset, int count)
        {
            // Always short-read. Length remains the open-handle observation before growth/shrink.
            var n = Math.Min(Math.Min(count, 2), bytes.Length - position);
            bytes.AsSpan(position, n).CopyTo(buffer.AsSpan(offset, n)); position += n; return n;
        }
        public override void Flush() => throw new NotSupportedException();
        public override long Seek(long offset, SeekOrigin origin) => throw new NotSupportedException();
        public override void SetLength(long value) => throw new NotSupportedException();
        public override void Write(byte[] buffer, int offset, int count) => throw new NotSupportedException();
    }

    // RFC1951 stored-block vectors: known raw bytes and explicit BFINAL, not generated by the decoder.
    public static byte[] StoredZlib(bool final)
    {
        byte[] raw = [0, 7, 14, 21, 28, 35, 42, 49, 56, 0, 70, 77, 84, 91, 98, 105, 112, 119];
        var z = new byte[2 + 5 + raw.Length + 4];
        z[0] = 0x78; z[1] = 0x01; z[2] = final ? (byte)1 : (byte)0;
        BinaryPrimitives.WriteUInt16LittleEndian(z.AsSpan(3), (ushort)raw.Length);
        BinaryPrimitives.WriteUInt16LittleEndian(z.AsSpan(5), (ushort)~raw.Length);
        raw.CopyTo(z, 7);
        uint a = 1, b = 0; foreach (var v in raw) { a = (a + v) % 65521; b = (b + a) % 65521; }
        BinaryPrimitives.WriteUInt32BigEndian(z.AsSpan(z.Length - 4), (b << 16) | a);
        return z;
    }

    public static IEnumerable<object[]> InvalidEnds()
    {
        var good = StoredZlib(true);
        yield return ["BFINAL=0", StoredZlib(false)];
        yield return ["junk plus duplicated Adler", good.Concat("junk"u8.ToArray()).Concat(good[^4..]).ToArray()];
        yield return ["second zlib stream plus duplicated Adler", good.Concat(TestPngs.Zlib([])).Concat(good[^4..]).ToArray()];
        for (var n = 1; n <= 4; n++) yield return [$"trailer truncated {n}", good[..^n]];
    }

    [Theory]
    [MemberData(nameof(InvalidEnds))]
    public void Unfinished_or_trailing_zlib_is_refused(string why, byte[] z)
    {
        var e = Assert.Throws<InvalidDataException>(() => PngCodec.Decode(TestPngs.WithIdat(2, 2, 8, 6, z)));
        Assert.NotEmpty(e.Message); Assert.NotEmpty(why);
    }

    [Fact]
    public void Final_stored_block_and_its_actual_trailer_are_accepted()
    {
        Assert.Equal(new byte[] { 21, 14, 7, 28, 49, 42, 35, 56, 84, 77, 70, 91, 112, 105, 98, 119 },
            PngCodec.Decode(TestPngs.WithIdat(2, 2, 8, 6, StoredZlib(true))).Bgra);
    }

    [Theory]
    [InlineData("IDAT")]
    [InlineData("prVt")]
    public void Empty_chunks_have_constant_metadata_allocation(string type)
    {
        var start = new List<byte> { 137, 80, 78, 71, 13, 10, 26, 10 };
        TestPngs.Chunk(start, "IHDR", TestPngs.Ihdr(2, 2, 8, 6, false));
        var chunk = new List<byte>(); TestPngs.Chunk(chunk, type, []);
        const int count = 100_000;
        var tail = new List<byte>(); TestPngs.Chunk(tail, "IDAT", StoredZlib(true)); TestPngs.Chunk(tail, "IEND", []);
        var png = new byte[start.Count + count * chunk.Count + tail.Count];
        start.ToArray().CopyTo(png, 0);
        for (var n = 0; n < count; n++) chunk.ToArray().CopyTo(png, start.Count + n * chunk.Count);
        tail.ToArray().CopyTo(png, start.Count + count * chunk.Count);
        PngCodec.Decode(TestPngs.WithIdat(2, 2, 8, 6, StoredZlib(true))); // warm static state
        var before = GC.GetAllocatedBytesForCurrentThread();
        Assert.Equal(16, PngCodec.Decode(png).Bgra.Length);
        Assert.True(GC.GetAllocatedBytesForCurrentThread() - before < 200_000, "per-chunk allocation amplification");
    }

    [Fact]
    public void Indexed_palette_cannot_exceed_bit_depth_range()
    {
        var png = new List<byte> { 137, 80, 78, 71, 13, 10, 26, 10 };
        TestPngs.Chunk(png, "IHDR", TestPngs.Ihdr(1, 1, 1, 3, false));
        TestPngs.Chunk(png, "PLTE", new byte[9]);
        TestPngs.Chunk(png, "IDAT", TestPngs.Zlib([0, 0])); TestPngs.Chunk(png, "IEND", []);
        Assert.Throws<InvalidDataException>(() => PngCodec.Decode(png.ToArray()));
    }
}
